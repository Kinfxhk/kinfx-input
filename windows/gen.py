"""Stage the Windows build inputs on the host (needs python + the librime msvc-x64 release).

  python windows/gen.py <librime dist dir>

Writes windows/build/stage/: data/ (prelude + KINFX schemas, prebuilt with the Windows
rime_deployer), rime/ (dll, lib, header), spec.h (settings spec for the TIP),
app-info.json, settings-spec.json, kinfx.ico. Then build.cmd runs on a machine with MSVC.
"""
import json
import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RIME = os.path.abspath(sys.argv[1])
S = os.path.join(HERE, "build", "stage")
shutil.rmtree(S, ignore_errors=True)
D = os.path.join(S, "data")
os.makedirs(D)

for n in os.listdir(os.path.join(ROOT, "engine", "prelude")):
    if n.endswith(".yaml"):
        shutil.copy(os.path.join(ROOT, "engine", "prelude", n), D)
shutil.copytree(os.path.join(ROOT, "engine", "rime"), D, dirs_exist_ok=True)
p = os.path.join(D, "default.yaml")
s = open(p, encoding="utf-8").read()
s2 = re.sub(r"schema_list:\n(  - schema: \w+\n)+", "schema_list:\n  - schema: kinfx_quick\n", s)
assert s2 != s
open(p, "w", encoding="utf-8", newline="\n").write(s2)
u = tempfile.mkdtemp()
subprocess.run([os.path.join(RIME, "bin", "rime_deployer.exe"), "--build", u, D, os.path.join(D, "build")],
               env=dict(os.environ, PATH=os.path.join(RIME, "lib") + os.pathsep + os.environ["PATH"]),
               capture_output=True)
shutil.rmtree(u, ignore_errors=True)
for t in ("kinfx_quick", "kinfx_quick_phrase", "kinfx_en", "kinfx_names", "kinfx_assoc"):
    assert os.path.exists(os.path.join(D, "build", t + ".table.bin")), "prebuild failed: " + t

R = os.path.join(S, "rime")
os.makedirs(R)
for a, b in (("lib/rime.dll", "rime.dll"), ("lib/rime.lib", "rime.lib"), ("include/rime_api.h", "rime_api.h")):
    shutil.copy(os.path.join(RIME, a), os.path.join(R, b))
shutil.copy(os.path.join(ROOT, "mac", "Sources", "Shim", "kx_shim.c"), R)
shutil.copy(os.path.join(ROOT, "mac", "Sources", "Shim", "kx_shim.h"), R)
for n in ("app-info.json", "settings-spec.json"):
    shutil.copy(os.path.join(ROOT, n), S)

# spec.h: the TIP validates settings.json and writes the Rime patch from this table.
spec = json.load(open(os.path.join(ROOT, "settings-spec.json"), encoding="utf-8"))["settings"]
out = ["// generated by windows/gen.py from settings-spec.json", "struct KxOpt { const char *v; const char *rime; };",
       "struct KxSpec { const char *key; const char *rime_key; int n; KxOpt opts[4]; };",
       "static const KxSpec kSpec[] = {"]
for e in spec:
    opts = ", ".join('{"%s", "%s"}' % (v, e.get("rime_value", {}).get(v, v)) for v, _ in e["options"])
    out.append('  {"%s", %s, %d, {%s}},' % (e["key"], '"%s"' % e["rime_key"] if e["rime_key"] else "nullptr",
                                           len(e["options"]), opts))
out.append("};")
open(os.path.join(S, "spec.h"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")


# kinfx.ico: 32x32 rounded dark tile with a light "K" stroke (no image library needed).
def ico(size=32):
    px = []
    for y in range(size - 1, -1, -1):  # BMP rows bottom-up
        for x in range(size):
            inside = 2 <= x < size - 2 and 2 <= y < size - 2
            k = (9 <= x <= 12 and 7 <= y <= 24) or (abs((x - 12) - abs(y - 16)) <= 1 and 12 <= x <= 23 and 7 <= y <= 24)
            c = (0xF0, 0xE6, 0xDC, 255) if k else (0x5A, 0x3E, 0x2E, 255) if inside else (0, 0, 0, 0)
            px.append(struct.pack("BBBB", c[2], c[1], c[0], c[3]))
    bmp = struct.pack("<IiiHHIIiiII", 40, size, size * 2, 1, 32, 0, 0, 0, 0, 0, 0) + b"".join(px) + b"\0" * (size * size // 8)
    return struct.pack("<HHH", 0, 1, 1) + struct.pack("<BBBBHHII", size, size, 0, 0, 1, 32, len(bmp), 22) + bmp


open(os.path.join(S, "kinfx.ico"), "wb").write(ico())
for n in ("build.cmd", "installer.iss", "ChineseTraditional.isl", "enable.ps1", "test-notepad.ps1", "kx.rc"):
    shutil.copy(os.path.join(HERE, n), S)
for d in ("tip", "settings"):
    shutil.copytree(os.path.join(HERE, d), os.path.join(S, d))
print("staged:", S)
